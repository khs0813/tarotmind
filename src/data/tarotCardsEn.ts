function translateKeywords(keywords: string[]): string[] {
  return [...new Set(keywords.map((keyword) => keywordTranslations[keyword] ?? 'reflection'))];
}

function formatKeywords(keywords: string[]): string {
  return keywords.slice(0, 3).join(', ');
}

function buildMajorCard(card: TarotCard): TarotCard {
  const keywords = translateKeywords(card.keywords);
  const keywordText = formatKeywords(keywords);
  const tone = majorTone[card.id] ?? `${card.nameEn} highlights ${keywordText}.`;
  const primary = keywords[0] ?? 'awareness';

  return {
    ...card,
    nameKo: card.nameEn,
    keywords,
    upright: {
      general: `${card.nameEn} points to themes of ${keywordText}. ${tone} In a general reading, notice how this theme is already moving through the situation.`,
      love: `${card.nameEn} in love highlights themes of ${keywordText}. It asks you to look at the relationship honestly and choose a response that respects both emotion and reality.`,
      career: `${card.nameEn} in career readings points to themes of ${keywordText}. Use it to review your current direction, responsibilities, and next practical move.`,
      money: `${card.nameEn} in money readings brings attention to themes of ${keywordText}. Review spending, planning, and real conditions before making financial decisions.`,
      advice: `Work with the theme of ${primary} in a grounded way. Choose one action that makes the message practical today.`
    },
    reversed: {
      general: `Reversed, ${card.nameEn} can show that the theme of ${primary} is blocked, delayed, or pushed too far. Pause and check where the situation needs adjustment.`,
      love: `Reversed, ${card.nameEn} can show imbalance, avoidance, or pressure in a relationship. Slow down and clarify what is real.`,
      career: `Reversed, ${card.nameEn} can point to unclear direction, resistance, or a need to revise the plan before pushing ahead.`,
      money: `Reversed, ${card.nameEn} asks you to be careful with assumptions, timing, and practical details around money.`,
      advice: `Do not force the theme of ${primary}. Rebalance it before taking a bigger step.`
    },
    caution: `${card.nameEn} warns against turning the theme of ${primary} into pressure, denial, or a fixed conclusion.`,
    action: `Choose one small step that supports the theme of ${primary} without ignoring practical reality.`
  };
}

function buildMinorCard(card: TarotCard): TarotCard {
  const keywords = translateKeywords(card.keywords);
  const keywordText = formatKeywords(keywords);
  const suit = card.suit ? suitFocus[card.suit] : undefined;
  const theme = suit?.theme ?? keywordText;
  const primary = keywords[0] ?? 'awareness';

  return {
    ...card,
    nameKo: card.nameEn,
    keywords,
    upright: {
      general: `${card.nameEn} highlights ${keywordText} through themes of ${theme}. It shows a practical pattern that can be noticed and adjusted through everyday choices.`,
      love: `${card.nameEn} in love focuses on ${suit?.love ?? 'relationship patterns'}. Let the theme of ${primary} guide how you communicate and respond.`,
      career: `${card.nameEn} in career readings points to ${suit?.career ?? 'work patterns'}. Look for one realistic action that supports progress.`,
      money: `${card.nameEn} in money readings emphasizes ${suit?.money ?? 'resource management'}. Check the real numbers and the habit behind the choice.`,
      advice: `Use the theme of ${primary} constructively. Keep the action small, clear, and connected to the real situation.`
    },
    reversed: {
      general: `Reversed, ${card.nameEn} can show that the theme of ${primary} is blocked, rushed, or out of balance. Slow down and review the details.`,
      love: `Reversed, ${card.nameEn} may point to tension, avoidance, or unclear emotional timing. Choose honest but measured communication.`,
      career: `Reversed, ${card.nameEn} can show delay, scattered effort, or a need to refine the plan before moving forward.`,
      money: `Reversed, ${card.nameEn} asks you to review spending, timing, and assumptions before committing resources.`,
      advice: `Adjust the pace around ${primary}. Avoid extremes and return to the practical facts.`
    },
    caution: `${card.nameEn} asks you to notice where the theme of ${primary} could become too intense, too passive, or disconnected from reality.`,
    action: `Check one detail related to ${theme} and make the next step more deliberate.`
  };
}

export const tarotCardsEn: TarotCard[] = tarotCards.map((card) => (card.arcana === 'major' ? buildMajorCard(card) : buildMinorCard(card)));
